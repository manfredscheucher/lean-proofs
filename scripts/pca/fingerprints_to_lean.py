#!/usr/bin/env python3
"""Turn fingerprint files of rusty-arrangements into Lean test instances.

Usage: python3 scripts/fingerprints_to_lean.py <fingerprints.txt> <ModuleName> [outdir]

Writes <outdir>/<ModuleName>/A<i>.lean (default outdir: Pca/Instances) for line i (one module
per arrangement, so that lake checks them in parallel) and <outdir>/<ModuleName>.lean
importing them. Each file holds the fingerprint and its `Arrangement`, checked by
`native_decide`, the theorem that the `Arrangement` is described by the fingerprint
(`Describes`, `DescribesSigns`), and the values (p_2, p_3, |X'|) computed here. These values
are not independent evidence: same author and same dart conventions as the Lean code
(rusty-arrangements, src/arrangement.rs). The values are also printed.

Plain python3, standard library only.
"""

import ast
import os
import sys


def parse(line):
    """Parse `{1: [2, -2], 2: [1, -1]}` into a list of lists (circle c at index c-1)."""
    d = ast.literal_eval(line.strip())
    n = len(d)
    assert sorted(d) == list(range(1, n + 1)), line
    return [list(d[c]) for c in range(1, n + 1)]


def tables(fp):
    """sigma, alpha, curve on dart numbers 2k+dir (rusty-arrangements encoding)."""
    n = len(fp)
    entries = [e for lst in fp for e in lst]
    offsets = [0]
    for lst in fp:
        offsets.append(offsets[-1] + len(lst))
    circle = [c for c in range(n) for _ in fp[c]]
    pos = {}
    for c in range(n):
        for i, e in enumerate(fp[c]):
            pos[(c, e)] = offsets[c] + i
    partner = []
    for k, e in enumerate(entries):
        c, d = circle[k], abs(e) - 1
        partner.append(pos[(d, -(c + 1) if e > 0 else c + 1)])
    m = 2 * len(entries)
    sigma, alpha, curve = [0] * m, [0] * m, [0] * m
    for k, e in enumerate(entries):
        p = partner[k]
        order = [2 * k, 2 * p, 2 * k + 1, 2 * p + 1] if e > 0 else [2 * k, 2 * p + 1, 2 * k + 1, 2 * p]
        for j in range(4):
            sigma[order[j]] = order[(j + 1) % 4]
        c = circle[k]
        off, length, i = offsets[c], len(fp[c]), k - offsets[c]
        alpha[2 * k] = 2 * (off + (i + 1) % length) + 1
        alpha[2 * k + 1] = 2 * (off + (i - 1) % length)
        curve[2 * k] = curve[2 * k + 1] = c
    return sigma, alpha, curve


def orbits(perm):
    seen, result = [False] * len(perm), []
    for s in range(len(perm)):
        orb = []
        a = s
        while not seen[a]:
            seen[a] = True
            orb.append(a)
            a = perm[a]
        if orb:
            result.append(orb)
    return result


def stats(fp):
    """(numDarts, p_2, p_3, |X'|) computed from the face orbits of phi = sigma . alpha."""
    sigma, alpha, _ = tables(fp)
    m = len(sigma)
    phi = [sigma[alpha[a]] for a in range(m)]
    faces = orbits(phi)
    face_of = {a: f for f, orb in enumerate(faces) for a in orb}
    size = [len(orb) for orb in faces]
    crossings = orbits(sigma)
    euler = len(crossings) - m // 2 + len(faces)
    assert euler == 2, f"not on the sphere: V - E + F = {euler}"
    p2 = sum(1 for s in size if s == 2)
    p3 = sum(1 for s in size if s == 3)
    t = [len({face_of[a] for a in x if size[face_of[a]] == 3}) for x in crossings]
    return m, p2, p3, sum(1 for v in t if v == 3)


def lean_list(fp):
    return "[" + ", ".join("[" + ", ".join(str(e) for e in lst) + "]" for lst in fp) + "]"


def main():
    if len(sys.argv) not in (3, 4):
        sys.exit(__doc__)
    infile, module = sys.argv[1], sys.argv[2]
    outdir = sys.argv[3] if len(sys.argv) == 4 else os.path.join("Pca", "Instances")
    with open(infile) as f:
        fps = [parse(line) for line in f if line.strip()]
    n = len(fps[0])
    print(f"{infile}: {len(fps)} arrangements, n = {n}")
    print("index: numDarts p_2 p_3 |X'|")
    os.makedirs(os.path.join(outdir, module), exist_ok=True)
    header = [
        "/-",
        "Copyright (c) 2026 Manfred Scheucher. All rights reserved.",
        "Released under Apache 2.0 license as described in the file LICENSE.",
        "Authors: Manfred Scheucher",
        "",
        f"Generated by `scripts/fingerprints_to_lean.py` from `{os.path.basename(infile)}`",
        "(rusty-arrangements); do not edit by hand.",
        "-/",
    ]
    imports = []
    for idx, fp in enumerate(fps, 1):
        m, p2, p3, xp = stats(fp)
        print(f"  {idx}: {m} {p2} {p3} {xp}")
        out = header + [
            "import Pca.Fingerprint",
            "import Pca.Instances.Checks",
            "",
            "/-!",
            f"Line {idx} of `{os.path.basename(infile)}` as an `Arrangement`, with its axioms checked by",
            "`native_decide`, and the theorem that it is the arrangement of that line (`Describes`).",
            "The values `(p 2, p 3, |X'|)` were computed by the script (same conventions, not independent).",
            "-/",
            "",
            f"namespace Pca.Instances.{module}",
            "",
            "open Pca Pca.Arrangement",
            "",
            f"/-- Line {idx} of `{os.path.basename(infile)}`. -/",
            f"def fp{idx} : Fingerprint :=",
            f"  {lean_list(fp)}",
            "",
            f"/-- The arrangement of line {idx}. -/",
            f"def A{idx} : Arrangement {n} (Fin {m}) :=",
            f"  fp{idx}.toArrangement {n} {m} (by native_decide) (by native_decide) (by native_decide)",
            "    (by native_decide)",
            "",
            f"theorem A{idx}_describes : fp{idx}.Describes A{idx} ∧ fp{idx}.DescribesSigns A{idx} := by",
            "  native_decide",
            "",
            f"theorem A{idx}_values : (A{idx}.p 2, A{idx}.p 3, A{idx}.X'.card) = ({p2}, {p3}, {xp}) := by",
            "  native_decide",
            "",
            f"theorem A{idx}_basicFacts : A{idx}.BasicFacts := by native_decide",
            "",
        ]
        if n >= 4:
            out += [f"theorem A{idx}_notesFacts : A{idx}.NotesFacts := by native_decide", ""]
        out.append(f"end Pca.Instances.{module}")
        path = os.path.join(outdir, module, f"A{idx}.lean")
        with open(path, "w") as f:
            f.write("\n".join(out) + "\n")
        imports.append(f"import Pca.Instances.{module}.A{idx}")
    path = os.path.join(outdir, module + ".lean")
    with open(path, "w") as f:
        f.write("\n".join(header + imports) + "\n")
    print(f"wrote {path} and {len(fps)} files in {os.path.join(outdir, module)}")


if __name__ == "__main__":
    main()
